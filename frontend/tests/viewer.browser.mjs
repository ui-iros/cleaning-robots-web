import assert from "node:assert/strict";
import { mkdtemp, readFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { chromium } from "@playwright/test";
import { createServer } from "vite";

// Run from frontend/: node tests/viewer.browser.mjs
const server = await createServer({ server: { host: "127.0.0.1", port: 5182, strictPort: true } });
const screenshots = await mkdtemp(join(tmpdir(), "cleaning-robots-viewer-"));
await server.listen();
let browser;
try {
  browser = await chromium.launch({ headless: true, channel: "msedge" });
  const page = await browser.newPage({ viewport: { width: 1100, height: 1100 }, acceptDownloads: true });
  const errors = [], external = [];
  page.on("pageerror", (e) => errors.push(e.message));
  page.on("request", (request) => { if (/^https?:/.test(request.url()) && !request.url().startsWith("http://127.0.0.1:5182/")) external.push(request.url()); });
  await page.goto("http://127.0.0.1:5182/");
  await page.locator(".tk-canvas").waitFor();
  await page.screenshot({ path: join(screenshots, "desktop.png"), fullPage: true });
  assert.equal(await page.title(), "CleaningRobots-v0 | Policy viewer");
  assert.equal(await page.locator(".legend-item").count(), 7);
  assert.equal(await page.getByRole("link", { name: /paper/i }).count(), 0);
  const step = page.locator(".status-card").filter({ has: page.locator("dt", { hasText: /^Step$/ }) }).locator("dd");
  await page.getByLabel("Action", { exact: true }).selectOption("E");
  await page.getByRole("button", { name: "Step", exact: true }).click();
  assert.equal(await step.innerText(), "1/500");
  await page.getByRole("button", { name: "Reset", exact: true }).click();
  assert.equal(await step.innerText(), "0/500");
  await page.getByRole("button", { name: "Play", exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll(".status-card dd")[5].textContent !== "0/500");
  await page.getByRole("button", { name: "Pause", exact: true }).click();
  const paused = await step.innerText();
  await page.waitForTimeout(600);
  assert.equal(await step.innerText(), paused);
  await page.getByLabel("Layout", { exact: true }).selectOption("Random layout");
  await page.getByLabel("Rows", { exact: true }).fill("4");
  await page.getByLabel("Columns", { exact: true }).fill("5");
  await page.getByLabel("Obstacles", { exact: true }).fill("3");
  await page.getByRole("button", { name: "Apply & reset", exact: true }).click();
  assert.equal(await page.locator(".map-heading p").innerText(), "Random layout");
  // Export then import to verify Tkinter JSON compatibility through the actual UI.
  const jsonDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "Save config", exact: true }).click();
  const jsonPath = await (await jsonDownload).path();
  const saved = JSON.parse(await readFile(jsonPath, "utf8"));
  assert.equal(saved.environment, "CleaningRobots-v0");
  assert.equal(saved.config.grid_rows, 4); assert.equal(saved.config.obstacle.count, 3);
  await page.getByLabel("Layout", { exact: true }).selectOption("Custom layout");
  await page.getByRole("button", { name: "Edit layout", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("button", { name: "Clear", exact: true }).click();
  await dialog.getByRole("button", { name: /^Row 1, column 2,/ }).click();
  await dialog.getByRole("button", { name: /^Row 2, column 1,/ }).click();
  await dialog.getByRole("button", { name: "Apply & reset", exact: true }).click();
  assert.match(await dialog.getByRole("alert").innerText(), /reachable/);
  await dialog.getByRole("button", { name: "Clear", exact: true }).click();
  await dialog.getByRole("button", { name: "Dock", exact: true }).click();
  await dialog.getByRole("button", { name: /^Row 2, column 2,/ }).click();
  await dialog.getByRole("button", { name: "Obstacle", exact: true }).click();
  await dialog.getByRole("button", { name: /^Row 3, column 3,/ }).click();
  await dialog.getByRole("button", { name: "Apply & reset", exact: true }).click();
  assert.equal(await page.locator(".map-heading p").innerText(), "Custom layout");
  assert.equal(await page.locator(".status-card").filter({ hasText: "Position (row, col)" }).locator("dd").innerText(), "2, 2");
  await page.locator("input[type=file]").setInputFiles({ name: "config.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(saved)) });
  await page.waitForFunction(() => document.querySelector(".map-heading p").textContent === "Random layout");
  assert.equal(await page.getByLabel("Rows", { exact: true }).inputValue(), "4");
  await page.locator("input[type=file]").setInputFiles({ name: "bad.json", mimeType: "application/json", buffer: Buffer.from('{"environment":"wrong"}') });
  await page.getByRole("alert").waitFor();
  await page.getByRole("button", { name: "Reset", exact: true }).click();
  const pngDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "Save PNG", exact: true }).click();
  const png = await readFile(await (await pngDownload).path());
  assert.equal(png.subarray(1, 4).toString(), "PNG");
  // Every single-grid algorithm runs its exported trained policy.
  await page.getByLabel("Action", { exact: true }).selectOption("Policy");
  for (const algorithm of ["dqn", "ppo", "trpo", "a2c", "sac"]) {
    await page.getByLabel("Algorithm", { exact: true }).selectOption(algorithm);
    await page.waitForFunction(() => ![...document.querySelectorAll("button")].find((button) => button.textContent === "Step")?.disabled);
    await page.getByRole("button", { name: "Step", exact: true }).click();
    assert.equal(await step.innerText(), "1/500");
    assert.equal(await page.locator(".controller-status strong").innerText(), `${algorithm.toUpperCase()} policy`);
  }
  await page.getByRole("button", { name: "Multi-grid benchmark", exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll(".benchmark-card").length === 5);
  await page.getByRole("button", { name: "Step all", exact: true }).click();
  assert.equal(await page.locator(".benchmark-progress").innerText(), "Step 1/500");
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.screenshot({ path: join(screenshots, "benchmark-desktop.png"), fullPage: true });
  await page.getByRole("button", { name: "Run to horizon", exact: true }).click();
  await page.waitForFunction(() => document.querySelector(".benchmark-heading .dirt-pill")?.textContent === "COMPLETE");
  await page.locator(".benchmark-results > summary").click();
  assert.equal(await page.locator(".benchmark-table tbody tr").count(), 5);
  const rows = await page.locator(".benchmark-table tbody tr").allTextContents();
  rows.forEach((row) => assert.match(row, /500/));
  await page.getByRole("button", { name: "Reset benchmark", exact: true }).click();
  assert.equal(await page.locator(".benchmark-progress").innerText(), "Step 0/500");
  for (const name of ["DQN", "TRPO", "A2C", "SAC"]) await page.getByRole("checkbox", { name, exact: true }).uncheck();
  await page.waitForFunction(() => document.querySelectorAll(".benchmark-card").length === 1);
  assert.equal(await page.locator(".benchmark-card h2").innerText(), "PPO");
  await page.getByRole("checkbox", { name: "PPO", exact: true }).uncheck();
  await page.getByText("Select at least one algorithm.", { exact: true }).waitFor();
  await page.getByRole("checkbox", { name: "PPO", exact: true }).check();
  await page.waitForFunction(() => document.querySelectorAll(".benchmark-card").length === 1);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(screenshots, "mobile.png"), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, "Mobile must not overflow horizontally");
  assert.deepEqual(errors, []); assert.deepEqual(external, []);
  await page.getByRole("button", { name: "Single grid", exact: true }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, "Single-grid mobile must not overflow horizontally");
  // Loading failures must be visible rather than silently using random actions.
  await page.route("**/policies/ppo.json", (route) => route.fulfill({ status: 503, body: "Unavailable" }));
  await page.reload();
  await page.getByRole("alert").waitFor();
  assert.equal(await page.getByRole("button", { name: "Step", exact: true }).isDisabled(), true);
  await page.unroute("**/policies/ppo.json");
  await page.getByRole("button", { name: "Retry policy", exact: true }).click();
  await page.waitForFunction(() => ![...document.querySelectorAll("button")].find((button) => button.textContent === "Step")?.disabled);
  console.log(`Browser checks passed: manual/playback, config, 5 trained policies, 5-grid benchmark to horizon, algorithm selection, PNG, mobile, no backend requests. Screenshots: ${screenshots}`);
} finally {
  await browser?.close(); await server.close();
}
